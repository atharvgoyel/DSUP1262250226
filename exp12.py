stack = ["Plate 1", "Plate 2", "Plate 3"]
# Add new plates/PUSH to the top of the stack
stack.append("Plate 4")
stack.append("Plate 5")
print(stack)
# Remove the topmost plate/POP
print("Removed:", stack.pop())
print(stack)
# Remove the topmost plate again
print("Removed:", stack.pop())
print(stack)

