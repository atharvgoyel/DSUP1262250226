target = int(input("Enter the element to search: "))
low = 0
high = n - 1
found = False
while low <= high:
  mid = (low + high) // 2
  if arr[mid] == target:
    print("Element found at position:", mid)
    found = True
    break
  elif target < arr[mid]:
    high = mid - 1
  else:
    low = mid + 1
