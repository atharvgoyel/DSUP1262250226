def bubbleSort(arr):
  n = len(arr)
  for i in range(n):
    swapped = False
    for j in range(0, n - i - 1):
      if arr[j] > arr[j + 1]:
        arr[j], arr[j + 1] = arr[j + 1], arr[j]
        swapped = True
    if not swapped:
      break
  arr = [64, 34, 25, 12, 22, 11, 90]
  bubbleSort(arr)
  print(arr)

def insertionSort(arr):
  n = len(arr)
  if n <= 1:
    return
  for i in range(1, n):
    key = arr[i]
    j = i - 1
    while j >= 0 and key < arr[j]:
      arr[j + 1] = arr[j]
      j -= 1
    arr[j + 1] = key
  arr = [12, 11, 13, 5, -1]
  insertionSort(arr)
  print(arr)